pub trait MembershipAllocationClientModule: Send + 'static {
    /// Ask an allocator to register a membership. Args
    /// `{config?, identityCommitment, rate?, authType?, authPayload?,
    ///  authProvider?, authArgs?, discover?, allocatorPeerId?,
    ///  allocatorMultiaddr?, bootstrapPeers?}`.
    /// config names the registry (ConfigState account). Allocators
    /// advertising the (registry, authType) pair through libp2p service
    /// discovery are asked first (discover, default true; needs config and a
    /// node with discovery mounted) while none has acted on the request; the
    /// configured allocatorPeerId+allocatorMultiaddr pair, if any, comes
    /// after them. bootstrapPeers (`/…/p2p/<peerId>` multiaddrs) are peers
    /// of the DHT the allocators advertise on. This module asks through a
    /// libp2p node of its own, never through libp2p_module: it listens on
    /// loopback only, runs service discovery as a client, keeps one stored
    /// key (see peer_id) and is stopped once nothing has used it for 30 s.
    /// The node is brought up on the given peers; with none, discovery is
    /// unavailable and only a configured allocator is asked.
    /// authType names the auth vector: any type the target
    /// allocator's authVerifiers accept; this module knows no vector by
    /// name. Its payload comes from authPayload (raw hex, verbatim) or an
    /// authProvider module implementing the auth_vector producer contract
    /// (authArgs forwarded verbatim); an authType with neither is a vector
    /// that needs no payload. No authType at all is an unauthenticated
    /// request for an open allocator
    /// → `{leaf_index, id_commitment, config_account, allocatorPeerId,
    ///  discovered, tx_hash?}`.
    /// A failure is `{kind, error, reason?, allocatorPeerId?, discovered?,
    ///  unconfirmed?, discovery?}`. kind is what to branch on:
    /// invalid_request (arguments refused here), auth_failed (the
    /// authProvider could not produce the payload), no_provider (no
    /// allocator read the request; discovery says why: unavailable,
    /// not_joined or none_advertising), refused (an allocator refused;
    /// reason is its code), not_submitted (authorised, nothing reached the
    /// chain), unconfirmed (submitted, may still land; `unconfirmed: true`),
    /// failed (a reply that could not be used). allocatorPeerId and
    /// discovered name the allocator whose own reply ended the request.
    fn request(&mut self, args_json: String) -> String;
    /// The allocators currently advertising a (registry, authType) pair
    /// through libp2p service discovery. Args
    /// `{config, authType?, bootstrapPeers?}` (bootstrapPeers as in request)
    /// → `{serviceId, candidates:[{peerId, addrs}], joined, peers}`:
    /// candidates is empty when none is placed yet or this node joined no
    /// peer within 20 s (`joined` false); `peers` is its outbound peer count.
    /// A node that cannot discover answers `{kind: "no_provider", error}`.
    fn discover(&mut self, args_json: String) -> String;
    /// The peer id of the node this module asks allocators through, the
    /// identity an allocator sees for the `peer-any` and `peer-allowlist`
    /// auth types → `{peerId}`. It stays the same across restarts while the
    /// key file `allocation_node.key` in this module's persistence directory
    /// is kept; a host that gives the module no persistence path gets a new
    /// id at every start. A failure is `{kind: "failed", error}`.
    fn peer_id(&mut self) -> String;
    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {}
}

