#[derive(Default)]
struct AllocationClient;

fn reply(r: Result<serde_json::Value, serde_json::Value>) -> String {
    match r {
        Ok(v) | Err(v) => v.to_string(),
    }
}

impl MembershipAllocationClientModule for AllocationClient {
    fn request(&mut self, args_json: String) -> String {
        reply(client::request(&args_json))
    }

    fn discover(&mut self, args_json: String) -> String {
        reply(client::discover(&args_json))
    }

    fn on_context_ready(&mut self, _ctx: &RustModuleContext) {
        lp::init(&[lp::LIBP2P_MODULE]);
    }
}

#[no_mangle]
pub extern "Rust" fn logos_module_install() {
    install::<AllocationClient>();
}
